function makeContext() {
  const props = { PORTAL_URL: BASE, PORTAL_SECRET: SECRET, ALLOW_HTTP: 'yes', OFFER_SHEET_ID: OFFER_ID, NAPS_SHEET_IDS: PAY_ID };
  const http = req => {
    const out = execFileSync('curl', ['-s', '-o', '-', '-w', '\n%{http_code}', '-X', 'POST', req.url,
      '-H', 'Content-Type: ' + req.contentType, '-H', 'X-ESS-Timestamp: ' + req.headers['X-ESS-Timestamp'],
      '-H', 'X-ESS-Signature: ' + req.headers['X-ESS-Signature'], '--data-binary', '@-'], { input: req.payload }).toString();
    const i = out.lastIndexOf('\n');
    return { getResponseCode: () => Number(out.slice(i + 1)), getContentText: () => out.slice(0, i) };
  };
  const ctx = {
    console: { log: () => {} },
    PropertiesService: { getScriptProperties: () => ({ getProperty: k => props[k] == null ? null : props[k], setProperty: (k, v) => { props[k] = v; } }) },
    LockService: { getScriptLock: () => ({ tryLock: () => true, releaseLock: () => {} }) },
    SpreadsheetApp: { openById: id => ({ getSheetByName: t => (sheets[id] && sheets[id][t]) ? { getDataRange: () => ({ getDisplayValues: () => sheets[id][t].map(r => r.slice()) }) } : null }) },
    DriveApp: { getFileById: id => { if (!drive[id]) throw new Error('File not found'); return { getBlob: () => ({ getBytes: () => Array.from(drive[id]).map(b => (b > 127 ? b - 256 : b)) }) }; } },
    Utilities: {
      Charset: { UTF_8: 'utf8' },
      base64Encode: bytes => Buffer.from(bytes.map(b => b & 0xff)).toString('base64'),
      // Apps Script returns Java (signed) bytes
      computeHmacSha256Signature: (v, k) => Array.from(crypto.createHmac('sha256', Buffer.from(k, 'utf8')).update(Buffer.from(v, 'utf8')).digest()).map(b => (b > 127 ? b - 256 : b)),
    },
    UrlFetchApp: { fetch: (url, req) => http(req), fetchAll: reqs => reqs.map(http) },
    ScriptApp: { getProjectTriggers: () => [], newTrigger: () => ({ timeBased: () => ({ everyMinutes: () => ({ create: () => {} }) }) }) },
  };
  vm.createContext(ctx);
  vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'bridge', 'PortalSync.gs'), 'utf8'), ctx);
  ctx._props = props;
  return ctx;
}

async function api(body) {
  const r = await fetch(BASE + '/api', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  return r.json();
}
function signed(pathname, bodyObj, opts) {
  opts = opts || {};
  const body = JSON.stringify(bodyObj);
  const ts = String(opts.ts || Date.now());
  const sig = crypto.createHmac('sha256', opts.secret || SECRET).update(ts + '.' + body).digest('hex');
  return fetch(BASE + pathname, { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-ESS-Timestamp': ts, 'X-ESS-Signature': sig }, body });
}

test('PortalSync back-fill, idempotency, regeneration', { skip }, async () => {
  const gs = makeContext();
  // clean slate for these sheets
  for (const id of Object.keys(drive)) for (const kind of ['offer', 'payslip']) await signed('/ingest/remove', { kind, fileId: id });

  gs.syncToPortal();
  assert.match(gs._props.LAST_SYNC, /offers\+2 payslips\+2$/, gs._props.LAST_SYNC);
  gs.syncToPortal();
  assert.match(gs._props.LAST_SYNC, /offers\+0 payslips\+0$/, 'second run sends nothing new');

  // HR re-generates September -> new PDF id
  sheets[PAY_ID].Payroll[2][22] = '1SlipSep000000000000000000bb';
  gs.syncToPortal();
  assert.match(gs._props.LAST_SYNC, /offers\+0 payslips\+1$/);

  // a missing Drive file is reported, the rest continue
  sheets[PAY_ID].Payroll[3][20] = 'Generated'; sheets[PAY_ID].Payroll[3][22] = '1MissingFile00000000000000zz';
  gs.syncToPortal();
  assert.match(gs._props.LAST_SYNC, /errors 1: 1MissingFile.*File not found/);
});

test('employee sees only their own synced documents', { skip }, async () => {
  const login = await api({ action: 'loginPin', empCode: 'CFD90001', pin: '9174' });
  assert.ok(login.ok, 'CFD90001 should have PIN 9174 (run api.test.js first)');
  const s = login.session;
  const offers = await api({ action: 'myOffers', session: s });
  assert.ok(offers.ok, JSON.stringify(offers));
  assert.equal(offers.items.length, 1);
  const o = offers.items[0];
  assert.equal(o['Generated On'], '2023-10-20 11:02');
  assert.equal(o['Designation'], 'Team Member — Kitchen', 'non-ASCII survived signing');
  assert.equal(o['Net Salary'], 16000);
  assert.equal(o['Phone Number'], undefined, 'phone not sent to browser');
  const op = await api({ action: 'offerPdf', session: s, id: o.id });
  assert.equal(Buffer.from(op.base64, 'base64').toString(), pdf('offer deepa').toString());

  const slips = await api({ action: 'myPayslips', session: s });
  assert.equal(slips.items.length, 2);
  const sep = slips.items.find(x => x['Pay Month'] === 'September');
  assert.equal(sep['Basic Stipend'], 14000);
  assert.equal(sep['DBT Payable'], 1400);
  assert.equal(sep['Employee ID'], 'CFD90001');
  const sp = await api({ action: 'payslipPdf', session: s, id: sep.id });
  assert.equal(Buffer.from(sp.base64, 'base64').toString(), pdf('sep v2').toString(), 'regenerated PDF replaced the old one');

  // someone else can't open Deepa's documents by id
  const other = await api({ action: 'loginPin', empCode: 'CFD90002', pin: '3917' });
  assert.equal((await api({ action: 'myOffers', session: other.session })).items.length, 0);
  assert.equal((await api({ action: 'offerPdf', session: other.session, id: o.id })).ok, false);
  assert.equal((await api({ action: 'payslipPdf', session: other.session, id: sep.id })).ok, false);
});

test('ingest rejects bad signatures, stale timestamps and non-PDFs', { skip }, async () => {
  assert.equal((await signed('/ingest/known', {}, { secret: 'x'.repeat(40) })).status, 401);
  assert.equal((await signed('/ingest/known', {}, { ts: Date.now() - 10 * 60 * 1000 })).status, 401);
  const r = await fetch(BASE + '/ingest/known', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' });
  assert.equal(r.status, 401);
  const bad = await signed('/ingest/offer', { row: { Status: 'Sent', 'Offer URL': 'https://drive.google.com/file/d/1NotAPdf0000000000000000xx/view' }, pdf: Buffer.from('<html>').toString('base64') });
  assert.equal(bad.status, 400);
  const failed = await signed('/ingest/offer', { row: { Status: 'Failed' }, pdf: pdf('x').toString('base64') });
  assert.equal(failed.status, 400);
});
